"""
VTube Studio 动画配置说明

要让羽依的模型像 Neuro Sama 一样会动（眨眼、呼吸、身体晃动、说话张嘴），
需要在 VTube Studio 中进行以下设置。
"""

# ============================================================
# 第一步：启用 VTube Studio 内置动画
# ============================================================
#
# 打开 VTube Studio → 菜单栏「模型」→「模型设置」
#
# ✅ 勾选以下选项：
#
# 1. 自动眨眼 (Automatic Eye Blink)
#    - 设置 → 模型 → 启用「自动眨眼」
#    - 眨眼间隔建议：3-8 秒
#    - 眨眼持续时间：0.2 秒
#
# 2. 呼吸动画 (Breathing)  
#    - 设置 → 模型 → 启用「呼吸」
#    - 呼吸幅度：0.3-0.5
#    - 呼吸速度：1.0 倍
#
# 3. 物理模拟 (Physics)
#    - 设置 → 物理 → 确保已加载模型的 .physics3.json
#    - 这会让头发、衣服、身体有自然晃动
#    - 点击「重新加载物理」确保生效
#
# 4. 嘴型同步 (Lip Sync)
#    - 设置 → 音频 → 启用「嘴型同步」
#    - VTS 会自动检测系统声音播放并触发嘴型
#    - 任何通过电脑扬声器播放的声音都会让羽依张嘴
#
# ============================================================
# 第二步：通过脚本触发的动画（已实现）
# ============================================================
#
# main_vts.py 会自动做：
# - 每 20 秒触发一次模型轻微移动 → 物理晃动
# - 30% 概率触发眨眼表情
# - 情绪切换时自动切换表情文件
#
# ============================================================
# 第三步：TTS 语音 → 嘴型同步
# ============================================================
#
# 当羽依"说话"时，播放 TTS 音频：
# - VTS 检测到系统音频 → 自动张嘴
# - 音频停止 → 嘴自动闭上
#
# 安装 TTS 依赖：
#   pip install edge-tts
#
# 运行测试：
#   python -c "
# import asyncio, edge_tts
# async def t():
#     c = edge_tts.Communicate('你好，我是羽依', 'zh-CN-XiaoxiaoNeural')
#     await c.save('hello.mp3')
# asyncio.run(t())
# "
#   然后播放 hello.mp3，VTS 会自动嘴型同步
#
# ============================================================
# 第四步：Neuro Sama 的做法
# ============================================================
#
# Neuro Sama 其实做的就是：
# 1. VTube Studio 渲染 Live2D 模型（已内置眨眼/呼吸/物理）
# 2. 通过 WebSocket API 控制表情切换
# 3. 使用 TTS 生成语音 → 音频播放 → VTS 自动嘴型同步
# 4. 定期小幅度移动模型 → 触发物理晃动
# 5. 有时通过面部捕捉（摄像头）实现头部跟随
#
# 我们的方案：
# ✅ 1-4 全部实现
# ⬜ 5 可选：如需头部跟随，可在 VTS 设置 → 摄像头 中启用
